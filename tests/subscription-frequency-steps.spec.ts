import { test, expect } from "./fixtures";

test("quantidade e frequencia no mesmo card, aplicacao a todos e excecoes individuais", async ({ page }, testInfo) => {
  await page.goto("/carrinho");
  await page.getByRole("button", { name: "Criar compra recorrente", exact: true }).click();
  const next = page.getByRole("button", { name: "Continuar para entrega" });
  const milk = page.locator(".subscription-product").filter({ has: page.getByRole("checkbox", { name: "Incluir Leite integral Shefa na compra recorrente" }) });
  const paper = page.locator(".subscription-product").filter({ has: page.getByRole("checkbox", { name: "Incluir Papel higiênico folha dupla na compra recorrente" }) });
  await milk.getByRole("checkbox").check();
  await paper.getByRole("checkbox").check();
  await expect(milk.getByLabel("Frequência de Leite integral Shefa")).toHaveValue("");
  await expect(milk.locator("output")).toHaveText("0");
  await expect(next).toBeDisabled();
  await milk.getByRole("button", { name: "Aumentar quantidade" }).click();
  await paper.getByRole("button", { name: "Aumentar quantidade" }).click();
  await expect(next).toBeDisabled();
  await page.getByRole("combobox", { name: /Frequência para todos/ }).selectOption("Semanal");
  await page.getByRole("button", { name: "Aplicar frequência a todos" }).click();
  await expect(milk.getByRole("combobox")).toHaveValue("Semanal");
  await expect(paper.getByRole("combobox")).toHaveValue("Semanal");
  await expect(next).toBeEnabled();
  await paper.getByRole("combobox").selectOption("Mensal");
  await milk.getByRole("combobox").selectOption("Quinzenal");
  await page.reload();
  await expect(milk.locator("output")).toHaveText("1");
  await expect(milk.getByRole("combobox")).toHaveValue("Quinzenal");
  await expect(paper.getByRole("combobox")).toHaveValue("Mensal");
  await expect(page.getByRole("navigation", { name: "Etapas do checkout" }).getByRole("link")).toHaveCount(4);
  await page.goto("/assinatura/frequencia");
  await expect(page).toHaveURL("/assinatura/configurar");
  await expect(milk.getByRole("combobox")).toHaveValue("Quinzenal");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: `test-results/${testInfo.project.name}-combined-products.png`, fullPage: true });
  await next.click();
  await expect(page).toHaveURL("/assinatura/entrega");
  await expect(page.getByRole("list", { name: "Produtos · Quinzenal" })).toContainText("Leite integral Shefa");
  await expect(page.getByRole("list", { name: "Produtos · Mensal" })).toContainText("Papel higiênico folha dupla");
  await page.getByRole("link", { name: "Voltar", exact: true }).click();
  await expect(page).toHaveURL("/assinatura/configurar");
  await expect(paper.getByRole("combobox")).toHaveValue("Mensal");
});

test("acesso direto a entrega exige quantidade e frequencia definidas", async ({ page }) => {
  await page.goto("/assinatura/configurar");
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem("covabra-prototype-v1")!);
    state.draft.items = [{ productId: "leite", quantity: 0, frequency: "Semanal" }];
    state.draft.frequencyPending = ["leite"];
    localStorage.setItem("covabra-prototype-v1", JSON.stringify(state));
  });
  await page.goto("/assinatura/entrega");
  await expect(page.getByRole("heading", { name: "Defina a quantidade dos produtos" })).toBeVisible();
  await page.getByRole("link", { name: "Voltar aos produtos" }).click();
  await page.locator(".subscription-product.selected").getByRole("button", { name: "Aumentar quantidade" }).click();
  await page.goto("/assinatura/entrega");
  await expect(page.getByRole("heading", { name: "Escolha a frequência dos produtos" })).toBeVisible();
  await page.getByRole("link", { name: "Escolher frequências" }).click();
  await expect(page).toHaveURL("/assinatura/configurar");
  await expect(page.getByRole("button", { name: "Continuar para entrega" })).toBeDisabled();
});

test("aplicar a todos considera apenas os produtos incluidos no momento", async ({ page }) => {
  await page.goto("/carrinho");
  await page.getByRole("button", { name: "Criar compra recorrente", exact: true }).click();
  const apply = page.getByRole("button", { name: "Aplicar frequência a todos" });
  const bulk = page.getByRole("combobox", { name: /Frequência para todos/ });
  const milk = page.locator(".subscription-product").filter({ has: page.getByRole("checkbox", { name: "Incluir Leite integral Shefa na compra recorrente" }) });
  const paper = page.locator(".subscription-product").filter({ has: page.getByRole("checkbox", { name: "Incluir Papel higiênico folha dupla na compra recorrente" }) });
  const next = page.getByRole("button", { name: "Continuar para entrega" });
  await expect(bulk).toBeDisabled();
  await expect(apply).toBeDisabled();
  await milk.getByRole("checkbox").check();
  await bulk.selectOption("Semanal");
  await apply.click();
  await expect(next).toBeDisabled();
  await milk.getByRole("button", { name: "Aumentar quantidade" }).click();
  await expect(next).toBeEnabled();
  await paper.getByRole("checkbox").check();
  await paper.getByRole("button", { name: "Aumentar quantidade" }).click();
  await expect(paper.getByRole("combobox")).toHaveValue("");
  await expect(next).toBeDisabled();
  await bulk.selectOption("Mensal");
  await apply.click();
  await expect(milk.getByRole("combobox")).toHaveValue("Mensal");
  await expect(paper.getByRole("combobox")).toHaveValue("Mensal");
  await expect(next).toBeEnabled();
  await milk.getByRole("checkbox").uncheck();
  await bulk.selectOption("Semanal");
  await apply.click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("covabra-prototype-v1")!));
  expect(saved.draft.items).toEqual([{ productId: "papel", quantity: 1, frequency: "Semanal" }]);
});
