import { test, expect } from "./fixtures";

test("selecionar começa em zero e todos os produtos precisam de quantidade positiva", async ({ page }) => {
  await page.goto("/minhas-assinaturas");
  await page.getByRole("link", { name: "Nova assinatura", exact: true }).click();
  await expect(page).toHaveURL("/assinatura/configurar");
  const milk = page.locator(".subscription-product").filter({ has: page.getByRole("heading", { name: "Leite integral Shefa", exact: true }) });
  const coffee = page.locator(".subscription-product").filter({ has: page.getByRole("heading", { name: "Café torrado e moído", exact: true }) });
  const next = page.getByRole("button", { name: "Continuar para entrega" });
  await milk.getByRole("checkbox").check();
  await expect(milk.locator("output")).toHaveText("0");
  await expect(milk.locator(".product-price strong")).toHaveText("R$ 0,00");
  await expect(milk.getByRole("button", { name: "Diminuir quantidade" })).toBeDisabled();
  await milk.getByRole("combobox").selectOption("Toda semana");
  await expect(next).toBeDisabled();
  await milk.getByRole("button", { name: "Aumentar quantidade" }).click();
  await expect(next).toBeEnabled();
  await coffee.getByRole("checkbox").check();
  await coffee.getByRole("combobox").selectOption("Todo mês");
  await expect(coffee.locator("output")).toHaveText("0");
  await expect(next).toBeDisabled();
  await coffee.getByRole("checkbox").uncheck();
  await expect(next).toBeEnabled();
  await milk.getByRole("button", { name: "Diminuir quantidade" }).click();
  await expect(next).toBeDisabled();
  await page.reload();
  await expect(milk.locator("output")).toHaveText("0");
  await page.goto("/assinatura/entrega");
  await expect(page.getByRole("heading", { name: "Defina a quantidade dos produtos" })).toBeVisible();
  await page.goto("/assinatura/revisao");
  await expect(page.getByRole("heading", { name: "Defina a quantidade dos produtos" })).toBeVisible();
  await page.getByRole("link", { name: "Voltar aos produtos" }).click();
  await expect(page).toHaveURL("/assinatura/configurar");
  await milk.getByRole("checkbox").uncheck();
  await milk.getByRole("checkbox").check();
  await expect(milk.locator("output")).toHaveText("0");
  await milk.getByRole("combobox").selectOption("Toda semana");
  await milk.getByRole("button", { name: "Aumentar quantidade" }).click();
  await next.click();
  await expect(page).toHaveURL("/assinatura/entrega");
});

test("editar não salva quantidade zero e o carrinho continua com mínimo de um", async ({ page }) => {
  await page.goto("/minhas-assinaturas/00124/editar");
  const milk = page.locator(".subscription-product").filter({ has: page.getByRole("heading", { name: "Leite integral Shefa", exact: true }) });
  await expect(milk.locator("output")).toHaveText("4");
  for (let count = 0; count < 4; count++) await milk.getByRole("button", { name: "Diminuir quantidade" }).click();
  await expect(milk.locator("output")).toHaveText("0");
  await expect(page.getByRole("button", { name: "Salvar alterações" })).toBeDisabled();
  await milk.getByRole("button", { name: "Aumentar quantidade" }).click();
  await page.getByRole("button", { name: "Salvar alterações" }).click();
  await expect(page).toHaveURL("/minhas-assinaturas/00124");
  await page.reload();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("covabra-prototype-v1")!).subscriptions.find((subscription: { id: string }) => subscription.id === "00124"));
  expect(saved.items.find((item: { productId: string }) => item.productId === "leite").quantity).toBe(1);
  await page.goto("/carrinho");
  const cartMilk = page.locator(".cart-item").first();
  for (let count = 0; count < 3; count++) await cartMilk.getByRole("button", { name: "Diminuir quantidade" }).click();
  await expect(cartMilk.locator("output")).toHaveText("1");
  await expect(cartMilk.getByRole("button", { name: "Diminuir quantidade" })).toBeDisabled();
});
